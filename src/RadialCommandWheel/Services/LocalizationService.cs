    public static void ApplyLanguage(AppLanguage language)
    {
        CurrentLanguage = language;
        var dictionary = language == AppLanguage.Arabic ? Arabic : English;
        var application = Application.Current;
        if (application is not null)
        {
            foreach (var key in AppliedKeys)
            {
                application.Resources.Remove(key);
            }

            AppliedKeys.Clear();
            foreach (var pair in dictionary)
            {
                application.Resources[pair.Key] = pair.Value;
                AppliedKeys.Add(pair.Key);
            }
        }

        var culture = language == AppLanguage.Arabic
            ? CultureInfo.GetCultureInfo("ar-SA")
            : CultureInfo.GetCultureInfo("en-US");
        CultureInfo.CurrentUICulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
    }

    public static string Get(string key)
    {
        var dictionary = CurrentLanguage == AppLanguage.Arabic ? Arabic : English;
        if (dictionary.TryGetValue(key, out var translated))
        {
            return translated;
        }

        return English.TryGetValue(key, out var fallback) ? fallback : key;
    }

    public static string Format(string key, params object[] arguments) =>
        string.Format(Get(key), arguments);

    public static string TypeName(WheelItemType type) => Get(type switch
    {
        WheelItemType.Application => "ApplicationType",
        WheelItemType.File => "FileType",
        WheelItemType.Folder => "FolderType",
        WheelItemType.Command => "CommandType",
        WheelItemType.Group => "GroupType",
        _ => "FileType"
    });

    public static string IconSourceName(IconSourceKind source) => Get(source switch
    {
        IconSourceKind.Automatic => "IconAutomatic",
        IconSourceKind.BuiltIn => "IconBuiltIn",
        IconSourceKind.File => "IconFile",
        _ => "IconAutomatic"
    });

    public static string ShortcutDisplay(ShortcutDefinition shortcut)
    {
        var parts = new List<string>();
        if (shortcut.Modifiers.HasFlag(ShortcutModifiers.Control)) parts.Add("Ctrl");
        if (shortcut.Modifiers.HasFlag(ShortcutModifiers.Alt)) parts.Add("Alt");
        if (shortcut.Modifiers.HasFlag(ShortcutModifiers.Shift)) parts.Add("Shift");
        if (shortcut.Modifiers.HasFlag(ShortcutModifiers.Windows)) parts.Add("Win");
        parts.Add(shortcut.VirtualKey switch
        {
            0x20 => Get("KeySpace"),
            0x0D => Get("KeyEnter"),
            0x09 => Get("KeyTab"),
            0x1B => Get("KeyEscape"),
            0x25 => Get("KeyLeft"),
            0x26 => Get("KeyUp"),
            0x27 => Get("KeyRight"),
            0x28 => Get("KeyDown"),
            _ => ShortcutDefinition.VirtualKeyName(shortcut.VirtualKey)
        });
        return string.Join(" + ", parts);
    }

    public static string ItemCaption(WheelItem item)
    {
        if (!string.IsNullOrWhiteSpace(item.Name))
        {
            return item.Name.Trim();
        }

        if (!string.IsNullOrWhiteSpace(item.Target))
        {
            var friendly = DisplayNameHelper.FromTarget(item.Target, item.Type);
            return string.IsNullOrWhiteSpace(friendly) ? TypeName(item.Type) : friendly;
        }

        return TypeName(item.Type);
    }
